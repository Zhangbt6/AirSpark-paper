for path in sorted((ROOT/'figures').glob('fig0[1-4]-*.svg')):
    if path.stem.endswith('-zh'): continue
    tree=ET.parse(path)
    for node in tree.iter():
        if 'font-family' in node.attrib:
            node.set('font-family', 'Microsoft YaHei, Noto Sans CJK SC, Arial, sans-serif')
        tag=node.tag.rsplit('}',1)[-1]
        if tag=='text':
            value=node.text or ''
            if value.startswith('AIRSPARK   /   FIGURE '):
                node.text='AIRSPARK / 图 '+value[-2:]
            else:
                assert value in TRANSLATIONS, f'Missing translation: {value}'
                node.text=TRANSLATIONS[value]
        elif tag=='title': node.text=TRANSLATIONS[node.text]
        elif tag=='desc':
            suffix='. Proposed research design, not measured results.'
            node.text=TRANSLATIONS[node.text.removesuffix(suffix)]+' 本图为研究设计示意，非实测结果。'
    target=path.with_stem(path.stem+'-zh')
    tree.write(target,encoding='utf-8',xml_declaration=True)
    print(target.name)
